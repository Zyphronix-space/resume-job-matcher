"""
Job-specific drafts: a tailored resume, a cover letter and an optional
outreach message.

These are produced by a fixed template, not a language model (none is
configured for this project), and are labelled that way. The template
only ever re-uses the candidate's own material:

  - skills: only ones found in the resume or confirmed on the profile;
  - experience, projects, education, certifications: the candidate's
    confirmed profile entries, or failing that their resume's own lines,
    reordered so entries relevant to this job come first;
  - evidence quotes: verbatim excerpts of the resume.

Anything the template can't truthfully fill (a motivation, a hiring
manager's name, a measurable result) becomes an [ADD: ...] placeholder for
the candidate to complete. check_draft() verifies a draft against that
contract and is run in the tests.
"""

import re

from resume_analyzer import find_skills
from skills_taxonomy import SKILL_TO_CATEGORY

GENERATOR = "template-v1"
NOTES_MARKER = "--- Notes for you (delete before sending) ---"
LABEL = (
    "DRAFT generated by a template from your own resume and profile. It is not written by AI and "
    "nothing in it is invented. Fill in every [ADD: ...] and check each line before you use it."
)

_ENTRY_LIMIT = 8


def _display(skill: str) -> str:
    special = {"sql": "SQL", "aws": "AWS", "gcp": "GCP", "html": "HTML", "css": "CSS", "php": "PHP",
               "nlp": "NLP", "oop": "OOP", "ci/cd": "CI/CD", "rest api": "REST APIs", "c#": "C#", "c++": "C++",
               "node.js": "Node.js", "next.js": "Next.js", "react.js": "React.js", ".net": ".NET",
               "fastapi": "FastAPI", "javascript": "JavaScript", "typescript": "TypeScript", "github": "GitHub",
               "gitlab": "GitLab", "mysql": "MySQL", "postgresql": "PostgreSQL", "mongodb": "MongoDB"}
    return special.get(skill, skill[:1].upper() + skill[1:])


def _lines(text: str) -> list[str]:
    out = []
    for raw in (text or "").splitlines():
        line = re.sub(r"^\s*[-*•·]\s*", "", raw).strip()
        if len(line) >= 3:
            out.append(line)
    return out


def _entries(profile: dict, resume_sections: dict, key: str, section: str) -> list[str]:
    confirmed = [e.strip() for e in (profile.get(key) or []) if isinstance(e, str) and e.strip()]
    return confirmed if confirmed else _lines(resume_sections.get(section, ""))


def _relevance_sorted(entries: list[str], job_skills: set[str]) -> list[str]:
    def score(entry: str) -> int:
        return len(find_skills(entry) & job_skills)
    return sorted(entries, key=lambda e: -score(e))[:_ENTRY_LIMIT]


def _contact(user) -> str:
    links = user.links or {}
    parts = [user.email, user.phone, user.location] + [v for v in links.values() if isinstance(v, str)]
    return " · ".join(p for p in parts if p)


def _skill_sets(profile: dict, cv_skills: set[str], assessment: dict) -> tuple[list[str], list[str], list[str]]:
    own = set(cv_skills) | {s.lower() for s in (profile.get("skills") or []) if isinstance(s, str)}
    importance = assessment.get("skill_importance") or {}
    evidenced = assessment.get("evidence_lines") or {}
    rank = {"Critical": 0, "High": 1, "Medium": 2}
    # Skills shown in use (a resume line outside the Skills list) lead;
    # within that, the posting's own emphasis decides.
    relevant = sorted(
        [s for s in assessment.get("matched_skills") or [] if s in own],
        key=lambda s: (s not in evidenced, rank.get((importance.get(s) or {}).get("level"), 3), s),
    )
    others = sorted(own - set(relevant))
    missing = [s for s in assessment.get("missing_skills") or [] if s not in own]
    return relevant, others, missing


def tailored_resume(user, profile: dict, cv_skills: set[str], resume_sections: dict, job: dict, assessment: dict) -> str:
    relevant, others, missing = _skill_sets(profile, cv_skills, assessment)
    job_skills = set(assessment.get("matched_skills") or []) | set(assessment.get("missing_skills") or [])
    name = user.full_name or "[ADD: your name]"

    summary = (profile.get("summary") or "").strip() or (
        "[ADD: two or three sentences about you, in your own words."
        + (f" Mention {', '.join(_display(s) for s in relevant[:3])} only if you can back them up." if relevant else "")
        + "]"
    )
    out = [LABEL, "", name, _contact(user), "", f"Target role: {job['title']}" + (f" at {job['company']}" if job.get("company") else ""), ""]
    out += ["SUMMARY", summary, ""]
    if relevant or others:
        out += ["SKILLS"]
        if relevant:
            out.append("Relevant to this role: " + ", ".join(_display(s) for s in relevant))
        if others:
            out.append("Other: " + ", ".join(_display(s) for s in others))
        out.append("")

    for title, key, section in (("EXPERIENCE", "experience", "Work Experience"), ("PROJECTS", "projects", "Projects")):
        entries = _relevance_sorted(_entries(profile, resume_sections, key, section), job_skills)
        out.append(title)
        if entries:
            out += [f"- {e}" for e in entries]
            out.append("[ADD: a concrete outcome for the most relevant entry above, only if it's true and you can explain it]")
        else:
            out.append(f"[ADD: your {title.lower()}, if you have any]")
        out.append("")

    education = _entries(profile, resume_sections, "education", "Education")
    out += ["EDUCATION"] + ([f"- {e}" for e in education[:_ENTRY_LIMIT]] or ["[ADD: your education]"]) + [""]
    certifications = _entries(profile, resume_sections, "certifications", "Certifications")
    if certifications:
        out += ["CERTIFICATIONS"] + [f"- {e}" for e in certifications[:_ENTRY_LIMIT]] + [""]

    out.append(NOTES_MARKER)
    if missing:
        out.append("Left out because they weren't found in your resume or profile: "
                   + ", ".join(_display(s) for s in missing) + ". Add one only if you genuinely have it.")
    out.append("Entries are your own wording, reordered so the ones closest to this job come first.")
    return "\n".join(out).strip() + "\n"


def cover_letter(user, profile: dict, cv_skills: set[str], job: dict, assessment: dict) -> str:
    relevant, _, missing = _skill_sets(profile, cv_skills, assessment)
    relevant = [s for s in relevant if SKILL_TO_CATEGORY.get(s) != "Soft Skills"]
    evidence = assessment.get("evidence_lines") or {}
    company = job.get("company") or "[ADD: company name]"
    name = user.full_name or "[ADD: your name]"
    out = [LABEL, "", "Dear [ADD: the hiring manager's name if you know it, otherwise 'Hiring team'],", ""]
    out.append(f"I'm applying for the {job['title']} role at {company}. "
               "[ADD: one or two sentences on why this role and this company interest you, in your own words.]")
    out.append("")
    if relevant:
        out.append("The parts of my background closest to what you're looking for:")
        for skill in relevant[:3]:
            out.append(f"- {_display(skill)}: [ADD: one sentence on how you used it and what came of it]")
        out.append("")
    else:
        out += ["[ADD: the experience or projects most relevant to this role]", ""]
    out.append("[ADD: anything else relevant and true, e.g. availability or why you'd be a good fit for the team]")
    out += ["", "Thank you for considering my application.", "", "Kind regards,", name, _contact(user), ""]
    out.append(NOTES_MARKER)
    quotes = [(s, evidence[s]) for s in relevant[:3] if s in evidence]
    if quotes:
        out.append("From your resume, to help you write the lines above:")
        out += [f"- {_display(s)} ({e['section']}): “{e['line']}”" for s, e in quotes]
    unevidenced = [s for s in relevant[:3] if s not in evidence]
    if unevidenced:
        out.append("Only in your skills list, with no example in your resume: "
                   + ", ".join(_display(s) for s in unevidenced) + ". Keep these lines only if you can give one.")
    if missing:
        out.append("Not mentioned because they weren't found in your resume: " + ", ".join(_display(s) for s in missing) + ".")
    return "\n".join(out).strip() + "\n"


def outreach_message(user, profile: dict, cv_skills: set[str], job: dict, assessment: dict) -> str:
    relevant, _, _ = _skill_sets(profile, cv_skills, assessment)
    company = job.get("company") or "[ADD: company name]"
    skills_text = " and ".join(_display(s) for s in relevant[:2])
    out = [LABEL, "", "Hi [ADD: their name],", ""]
    out.append(f"I'm applying for the {job['title']} role at {company}."
               + (f" My background includes {skills_text}. [ADD: one specific example]." if skills_text else
                  " [ADD: one line on your most relevant experience]."))
    out.append("Would you be open to a short chat about the team, or point me to the right person?")
    out += ["", "Thanks,", user.full_name or "[ADD: your name]", ""]
    out.append(NOTES_MARKER)
    out.append("Nothing is sent automatically. Copy this into LinkedIn or email yourself if you choose to reach out.")
    return "\n".join(out).strip() + "\n"


def generate(kind: str, user, profile: dict, cv_skills: set[str], resume_sections: dict, job: dict, assessment: dict) -> str:
    if kind == "resume":
        return tailored_resume(user, profile, cv_skills, resume_sections, job, assessment)
    if kind == "cover_letter":
        return cover_letter(user, profile, cv_skills, job, assessment)
    if kind == "outreach":
        return outreach_message(user, profile, cv_skills, job, assessment)
    raise ValueError(kind)


_NUMBER_RE = re.compile(r"\d+(?:[.,]\d+)?%?")


def check_draft(draft: str, allowed_skills: set[str], source_texts: list[str]) -> list[str]:
    """Problems found in a draft's body (the notes section is excluded):
    a skill the candidate doesn't have, or a number that appears nowhere
    in their own material or the job's title."""
    body = draft.split(NOTES_MARKER, 1)[0]
    body = re.sub(r"\[ADD:[^\]]*\]", " ", body)
    problems = []
    for skill in sorted(find_skills(body) - set(allowed_skills)):
        problems.append(f"skill not supported by the resume or profile: {skill}")
    sources = "\n".join(source_texts)
    for number in set(_NUMBER_RE.findall(body)):
        if number not in sources:
            problems.append(f"number not found in the candidate's own material: {number}")
    return problems
